const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'..','CCDASTROWorkflowManager.js'),'utf8');
new vm.Script(source.replace(/^#.*$/gm,''));
const ctx=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function thirdPartyScriptRestriction('),source.indexOf('// Native workflow settings:')),ctx);
const start=source.indexOf('ProcessIconAdapter.prototype.configuredProcess = function()');
const end=source.indexOf('ProcessIconAdapter.prototype.execute',start);
ctx.ProcessIconAdapter=function(){};
ctx.errorMessage=String;
vm.runInContext(source.slice(start,end),ctx);
const adapter=new ctx.ProcessIconAdapter();
assert.throws(()=>adapter.configuredProcess(),/temporarily unavailable/);
assert.equal(adapter.available(),false);
assert.match(adapter.requirement(),/temporarily unavailable/);
assert.ok(source.includes('function defaultSyQonSettings()'));
console.log('Saved SyQon choices cannot bypass security restriction');
